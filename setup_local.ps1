# Local environment setup for tau2/GAIA benchmarks
# Installs uv, Python 3.14, psi-agent, tau2-bench, and GAIA data
# Run this AFTER merge_and_init.ps1

param(
    [string]$PsiRoot    = "C:\Users\hwm20\Downloads\psi-agent-main",
    [string]$Tau2Root   = "",
    [string]$RepoRoot   = $PSScriptRoot,
    [string]$GaiaDataRoot = ""
)

$ErrorActionPreference = "Stop"

Write-Host "`n=== Local Environment Setup ===`n" -ForegroundColor Cyan

# ---- 1. Install uv ----
Write-Host "[1/6] Checking uv..." -ForegroundColor Yellow
$uvFound = Get-Command uv -ErrorAction SilentlyContinue
if (-not $uvFound) {
    Write-Host "  uv not found. Installing..." -ForegroundColor Yellow
    # uv official installer for Windows
    powershell -ExecutionPolicy ByPass -c "irm https://astral.sh/uv/install.ps1 | iex"
    # Refresh PATH for current session
    $env:Path = [System.Environment]::GetEnvironmentVariable("Path","Machine") + ";" + [System.Environment]::GetEnvironmentVariable("Path","User")
    $uvFound = Get-Command uv -ErrorAction SilentlyContinue
    if (-not $uvFound) {
        Write-Host "  ERROR: uv installation failed. Please install manually from https://docs.astral.sh/uv/" -ForegroundColor Red
        exit 1
    }
}
Write-Host "  uv: $($uvFound.Source)" -ForegroundColor Green

# ---- 2. Install Python 3.14 via uv ----
Write-Host "`n[2/6] Installing Python 3.14..." -ForegroundColor Yellow
uv python install 3.14
$pyVersion = uv python find 3.14
Write-Host "  Python 3.14: $pyVersion" -ForegroundColor Green

# ---- 3. Install psi-agent ----
Write-Host "`n[3/6] Installing psi-agent..." -ForegroundColor Yellow
if (-not (Test-Path "$PsiRoot\pyproject.toml")) {
    Write-Host "  ERROR: psi-agent not found at $PsiRoot" -ForegroundColor Red
    Write-Host "  Please clone: git clone https://github.com/hys070414/psi-agent.git $PsiRoot"
    exit 1
}
# Create venv with Python 3.14 and install psi-agent in editable mode
Push-Location $PsiRoot
uv venv --python 3.14 .venv-benchmark
uv pip install -e ".[dev]" 2>$null || uv pip install -e "."
Pop-Location
Write-Host "  psi-agent installed at $PsiRoot (.venv-benchmark)" -ForegroundColor Green

# ---- 4. Clone tau2-bench ----
if (-not $Tau2Root) {
    $Tau2Root = Join-Path $RepoRoot "external" "tau2-bench"
}
Write-Host "`n[4/6] Setting up tau2-bench..." -ForegroundColor Yellow
if (Test-Path $Tau2Root) {
    Write-Host "  tau2-bench exists at $Tau2Root" -ForegroundColor Green
} else {
    Write-Host "  Cloning tau2-bench to $Tau2Root..." -ForegroundColor Yellow
    $tau2Parent = Split-Path $Tau2Root -Parent
    if (-not (Test-Path $tau2Parent)) { New-Item -ItemType Directory -Path $tau2Parent -Force | Out-Null }
    git clone https://github.com/sierra-research/tau2-bench.git $Tau2Root
}
# Install tau2-bench in the same venv
Push-Location $Tau2Root
if (Test-Path "pyproject.toml") {
    uv pip install -e .
} elseif (Test-Path "setup.py") {
    uv pip install -e .
} else {
    uv pip install -r requirements.txt 2>$null
    Write-Host "  (installed tau2-bench from requirements.txt)" -ForegroundColor Yellow
}
Pop-Location
Write-Host "  tau2-bench ready at $Tau2Root" -ForegroundColor Green

# ---- 5. Download GAIA data ----
Write-Host "`n[5/6] Downloading GAIA data..." -ForegroundColor Yellow
if (-not $GaiaDataRoot) {
    $GaiaDataRoot = Join-Path $RepoRoot "external" "gaia-data"
}
if (-not (Test-Path $GaiaDataRoot)) { New-Item -ItemType Directory -Path $GaiaDataRoot -Force | Out-Null }
$env:GAIA_DATA_ROOT = $GaiaDataRoot
# Use the merged repo's script to download GAIA
$gaiaScript = Join-Path $RepoRoot "scripts\psi_agent_benchmark.py"
if (Test-Path $gaiaScript) {
    & uv run --python 3.14 --project $PsiRoot python $gaiaScript download-gaia --gaia-data-root $GaiaDataRoot
} else {
    Write-Host "  GAIA script not found, will download on first run" -ForegroundColor Yellow
}
Write-Host "  GAIA data at $GaiaDataRoot" -ForegroundColor Green

# ---- 6. Write .env.local ----
Write-Host "`n[6/6] Writing .env.local..." -ForegroundColor Yellow
$envFile = Join-Path $RepoRoot ".env.local"
$envContent = @"
# Local environment for tau2/GAIA benchmarks
# Generated by setup_local.ps1

# psi-agent
PSI_ROOT=$PsiRoot

# tau2-bench
TAU2_ROOT=$Tau2Root

# uv
UV_PATH=$(Get-Command uv).Source

# GAIA
GAIA_DATA_ROOT=$GaiaDataRoot

# DeepSeek API (shared with remote TB)
PSI_AI_PROVIDER=openai
PSI_AI_MODEL=deepseek-chat
PSI_AI_BASE_URL=https://api.deepseek.com/v1

# tau2 user simulator
TAU2_USER_LLM=deepseek/deepseek-chat
"@
Set-Content -Path $envFile -Value $envContent -Encoding UTF8
Write-Host "  .env.local written to $envFile" -ForegroundColor Green

# ---- Summary ----
Write-Host "`n=== Setup Complete ===`n" -ForegroundColor Cyan
Write-Host "Local environment ready for tau2/GAIA."
Write-Host ""
Write-Host "Paths:"
Write-Host "  psi-agent:     $PsiRoot (.venv-benchmark)"
Write-Host "  tau2-bench:    $Tau2Root"
Write-Host "  GAIA data:     $GaiaDataRoot"
Write-Host "  .env.local:    $envFile"
Write-Host ""
Write-Host "Verify with:"
Write-Host "  python benchmark.py run -b tau2 --subset quick_3 --dry-run"
Write-Host "  python benchmark.py run -b gaia --subset level1_smoke --dry-run"
